"""Generate the KRIOS dark theme from the light stylesheets (viewer choice; light stays the default).

Run from the repo root after any stylesheet change:  python3 scripts/theme_dark.py
For each stylesheet it writes one block at the end, between the markers below, with rules scoped to
html[data-theme="dark"]. Light surfaces become the KRIOS night set (stage #0b1424, panels #10213a) and dark
text becomes ivory #f1e8d2; secondary text #c9c2b0; gold text #d9b674; links pale blue #8fb3d9 or terracotta.
Rules that pair a text colour with their own non-light background (gold buttons, dark headers) are left alone.
Images are never touched. Re-running replaces the block, so it never grows. Needs tinycss2 (pip).
"""
import os, re, sys
import tinycss2

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
START, END = "/* KRIOS dark theme: generated by scripts/theme_dark.py, do not edit by hand */", "/* end KRIOS dark theme */"
D = 'html[data-theme="dark"]'
STAGE, LIFT, PANEL = "#0b1424", "#0e1a2e", "#10213a"
IVORY, SECOND, GOLDTXT, LINK, TERRA = "#f1e8d2", "#c9c2b0", "#d9b674", "#8fb3d9", "#e8a083"

TEXT = {}
for v in ["var(--blue-800)", "var(--blue-900)", "var(--blue-700)", "var(--u-aegean-950)", "var(--u-aegean-900)",
          "var(--u-aegean-800)", "var(--u-ink)", "var(--u-charcoal)", "var(--u-charcoal-2)", "#1d1f23", "#22252a", "#1d1a14",
          "#14213a", "#0f2a43", "#0b2036", "#33373e", "#3d3d3d", "#101a2e", "#1c2d4d", "#000", "#000000", "#111", "#222"]:
    TEXT[v] = IVORY
for v in ["var(--u-aegean-700)", "#1a4a73", "#143a5c", "var(--u-aegean-500)", "#3f86b5", "#2a3a5c", "#33476e"]:
    TEXT[v] = LINK
for v in ["var(--u-stone-ink)", "#5a5546", "#4a4639", "#4a4336", "#474c55", "#3d3a2f", "#686d76", "#555", "#666"]:
    TEXT[v] = SECOND
for v in ["var(--u-gold-ink)", "#664c16", "#6b5020", "#6b4f12", "#8a6a2c", "#5c4400", "#8a3f27", "var(--u-terra-ink)"]:
    TEXT[v] = GOLDTXT
for v in ["#8c2a2a", "#7e2418"]:
    TEXT[v] = TERRA

SECTION_BG = ["var(--ivory)", "var(--ivory-2)", "var(--u-ivory)", "var(--u-ivory-2)", "#f6f0e2", "#ece3cd", "#ebe1c7",
              "#f5edd8", "var(--paper)", "#faf6ec", "var(--u-paper)", "var(--u-stone)"]
CARD_BG = ["#fffdf7", "#fff", "#ffffff", "white", "#fdfaf2", "#f7f3e8"]
BG = {v: LIFT for v in SECTION_BG}
BG.update({v: PANEL for v in CARD_BG})
BG.update({"#eef5ef": "#173a27", "#f8ecea": "#3d1d1d"})

VARS = {
    "site.css": "--paper:%s;--ink:%s;--ink-2:%s;--line:#2c3d5e;--gold-ink:%s;--red:%s" % (STAGE, IVORY, SECOND, GOLDTXT, TERRA),
    "krios.css": "--paper:%s;--ink:%s;--ink-2:%s;--line:#2c3d5e;--gold-ink:%s;--red:%s" % (STAGE, IVORY, SECOND, GOLDTXT, TERRA),
    "universe.css": "--u-stone:#2c3d5e;--u-stone-2:#3a4d70;--u-gold-ink:%s;--u-terra-ink:%s" % (GOLDTXT, TERRA),
    "guide.css": "",
    "sacred.css": "",
}
# Hand-written additions per file (things the generic pass cannot know).
EXTRA = {
    "site.css": [
        f"{D}{{color-scheme:dark}}",
        f"{D} body:not(.s-page){{background:{STAGE};color:{IVORY}}}",
        f"{D} .m-draft{{color:#6b4f12!important;background:#f3e3b8!important}}",
        f"{D} .explore a.tile,{D} .m-entry,{D} .m-card,{D} .m-src > div,{D} .m-chips a,{D} .m-chips button,{D} .m-opts button{{border-color:#2c3d5e}}",
        f"{D} .m-read{{border-color:rgba(241,232,210,.18)}}",
        f"{D} .m-read[open] summary{{border-bottom-color:rgba(241,232,210,.14)}}",
        f"{D} .m-chips button[aria-pressed=true]{{background:{IVORY};color:{STAGE};border-color:{IVORY}}}",
        f"{D} .m-ladder li:last-child span{{color:{STAGE}}}",
    ],
    "krios.css": [
        f"{D}{{color-scheme:dark}}",
        f"{D} body:not(.s-page){{background:{STAGE}!important;color:{IVORY}!important}}",
        f"{D} .k-main a:hover{{color:{IVORY}!important}}",
        f"{D} .k-main table,{D} .k-main td,{D} .k-main th{{border-color:#2c3d5e}}",
        f"{D} .k-main [style*=\"background\"]{{background:{PANEL}!important;color:{IVORY}!important}}",
        f"{D} .k-main [style*=\"color:#\"],{D} .k-main [style*=\"color: #\"]{{color:{IVORY}!important}}",
        # quiz pages keep their own colour variables in an inline block; give them night values
        f"{D} .k-quiz{{--bg:{STAGE};--text:{IVORY};--white:{IVORY};--dim:{SECOND};--gold:{GOLDTXT};--correct:#7fc49a;--wrong:{TERRA};--muted:{SECOND};--card:{PANEL};--border:#2c3d5e;--terracotta:{TERRA};--green:#7fc49a;--red:{TERRA}}}",
        f"{D} .explanation{{background:{LIFT}!important}}",
        # links page (inline styles)
        f"{D} .lk h1{{color:{IVORY}}}",
        f"{D} .lk a:not(.hi){{background:{PANEL}}}",
        f"{D} .k-quiz #options button{{background:{PANEL}}}",
        f"{D} .k-quiz #next-btn,{D} .k-quiz .share-btn{{background:{IVORY}!important;color:{STAGE}!important}}",
    ],
    "universe.css": [],
    "guide.css": [],
    "sacred.css": [],
}


def norm(v):
    return re.sub(r"\s+", " ", v.strip().lower().replace("!important", "")).strip()


def decls(block):
    out = []
    for d in tinycss2.parse_declaration_list(block, skip_comments=True, skip_whitespace=True):
        if d.type == "declaration":
            out.append((d.lower_name, tinycss2.serialize(d.value).strip(), d.important))
    return out


def scope(sel):
    parts = []
    for s in sel.split(","):
        s = s.strip()
        if not s:
            continue
        if s.startswith(":root") or s.startswith("html") or s == "body":
            continue  # :root variables and html-level rules are handled by VARS and EXTRA
        parts.append(f"{D} {s}")
    return ",".join(parts)


def rules_for(nodes):
    out = []
    for n in nodes:
        if n.type == "qualified-rule":
            sel = tinycss2.serialize(n.prelude).strip()
            ds = decls(n.content)
            bgs = [(v, imp) for k, v, imp in ds if k in ("background", "background-color")]
            own_dark_bg = any(norm(v) not in BG and norm(v) not in ("none", "transparent", "inherit") and not norm(v).startswith("linear-gradient(var(--gold)") for v, _ in bgs)
            new = []
            for k, v, imp in ds:
                nv = norm(v)
                bang = "!important" if imp else ""
                if k == "color" and nv in TEXT and not own_dark_bg:
                    new.append(f"color:{TEXT[nv]}{bang}")
                elif k in ("background", "background-color") and nv in BG:
                    new.append(f"background:{BG[nv]}{bang}")
            sc = scope(sel)
            if new and sc:
                out.append(f"{sc}{{{';'.join(new)}}}")
        elif n.type == "at-rule" and n.lower_at_keyword in ("media", "supports") and n.content:
            inner = rules_for(tinycss2.parse_rule_list(n.content, skip_comments=True, skip_whitespace=True))
            if inner:
                out.append(f"@{n.at_keyword} {tinycss2.serialize(n.prelude).strip()}{{{''.join(inner)}}}")
    return out


def build(name):
    path = os.path.join(ROOT, "assets", name)
    css = open(path, encoding="utf-8").read()
    css = re.sub(r"\n?" + re.escape(START) + r"[\s\S]*?" + re.escape(END) + r"\n?", "\n", css).rstrip() + "\n"
    rules = rules_for(tinycss2.parse_stylesheet(css, skip_comments=True, skip_whitespace=True))
    block = [START]
    if VARS[name]:
        block.append(f"{D}{{{VARS[name]}}}")
    block += rules + EXTRA[name]
    block.append(f"@media (prefers-reduced-motion:no-preference){{{D} body,{D} main{{transition:background-color .25s,color .25s}}}}" if name in ("site.css", "krios.css") else "")
    block.append(END)
    out = css + "\n".join(b for b in block if b) + "\n"
    open(path, "w", encoding="utf-8").write(out)
    return len(rules)


if __name__ == "__main__":
    for f in ["site.css", "krios.css", "universe.css", "guide.css"]:  # sacred.css is already a dark design
        print(f, build(f), "rules")
